const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');
const { COUNSELLOR_PERSONALITIES } = require('../config/constants');

const userSchema = new mongoose.Schema(
  {
    name: { type: String, required: [true, 'Name is required'], trim: true, maxlength: 60 },
    email: {
      type: String,
      required: [true, 'Email is required'],
      unique: true,
      lowercase: true,
      trim: true,
      match: [/^\S+@\S+\.\S+$/, 'Please provide a valid email'],
    },
    password: { type: String, required: [true, 'Password is required'], minlength: 6, select: false },
    preferences: {
      theme: { type: String, enum: ['light', 'dark'], default: 'light' },
      favoriteMusicCategories: { type: [String], default: [] },
      defaultCounsellorPersonality: {
        type: String,
        enum: COUNSELLOR_PERSONALITIES,
        default: 'warm_empathetic',
      },
      notificationsEnabled: { type: Boolean, default: true },
    },
    avatarColor: { type: String, default: '#6C5CE7' },
    role: { type: String, enum: ['user', 'admin'], default: 'user' },
    isActive: { type: Boolean, default: true },
    lastLoginAt: { type: Date },
  },
  { timestamps: true }
);

userSchema.pre('save', async function hashPassword(next) {
  if (!this.isModified('password')) return next();
  const salt = await bcrypt.genSalt(10);
  this.password = await bcrypt.hash(this.password, salt);
  next();
});

userSchema.methods.comparePassword = async function comparePassword(candidate) {
  return bcrypt.compare(candidate, this.password);
};

userSchema.methods.toSafeObject = function toSafeObject() {
  return {
    id: this._id,
    name: this.name,
    email: this.email,
    preferences: this.preferences,
    avatarColor: this.avatarColor,
    role: this.role,
    isActive: this.isActive,
    createdAt: this.createdAt,
  };
};

module.exports = mongoose.model('User', userSchema);
